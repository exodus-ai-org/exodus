export const artifactIcons: Record<string, IconSvgElement> = new Proxy(ICONS, {
  get(target, key) {
    if (typeof key !== 'string') return undefined
    if (key in target) return target[key]
    // Only an icon-shaped name gets the placeholder; `__esModule`, `default`
    // and the like stay undefined so module interop keeps working.
    return key.endsWith('Icon') ? target.HelpCircleIcon : undefined
  },
  has(target, key) {
    return typeof key === 'string' && (key in target || key.endsWith('Icon'))
  }
})
